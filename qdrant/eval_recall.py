#!/usr/bin/env python3
"""Recall@k pilot: dense vs. hybrid retrieval on benchmark items with gold sources.

    python qdrant/eval_recall.py --class-id <EVAL_CLASS_ID> \\
        --collection class_content_embeddings_hybrid_dev --out results/retrieval/recall_pilot.md

A retrieved hit matches a gold source when the file name matches (case-insensitive) and,
if the gold source names a page, the page matches too. Per item:
  recall@k = gold sources found in the top k / number of gold sources
  hit@k    = 1 if any gold source is in the top k
  RR       = 1 / rank of the first matching hit (0 if none in the top k)
Means are over items. Needs QDRANT_URL, QDRANT_API_KEY and GEMINI_API_KEY (query embeddings).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Sequence

QDRANT_DIR = Path(__file__).resolve().parent
REPO_DIR = QDRANT_DIR.parent
sys.path.insert(0, str(QDRANT_DIR))
sys.path.insert(0, str(REPO_DIR / "modal"))

from create_collection import ENV_FILE_PATH, load_env_file  # noqa: E402

MODES = ("dense", "hybrid")

SearchFn = Callable[[str, str], List[Dict[str, Any]]]  # (query, mode) -> hits


def load_gold_items(path: Path) -> List[Dict[str, Any]]:
    items = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        item = json.loads(line)
        if item.get("gold_sources"):
            items.append(item)
    return items


def hit_matches(hit: Dict[str, Any], gold: Dict[str, Any]) -> bool:
    file_name = str(hit.get("fileName") or "").strip().lower()
    if not file_name or file_name != str(gold.get("file_name") or "").strip().lower():
        return False
    gold_page = gold.get("page")
    return gold_page is None or hit.get("pageNumber") == gold_page


def score_item(hits: Sequence[Dict[str, Any]], gold_sources: Sequence[Dict[str, Any]], k: int) -> Dict[str, float]:
    top = list(hits)[:k]
    found = sum(1 for gold in gold_sources if any(hit_matches(hit, gold) for hit in top))
    first_rank = next(
        (rank for rank, hit in enumerate(top, start=1) if any(hit_matches(hit, gold) for gold in gold_sources)),
        None,
    )
    return {
        "recall": found / len(gold_sources),
        "hit": 1.0 if found else 0.0,
        "rr": 1.0 / first_rank if first_rank else 0.0,
    }


def evaluate(items: Sequence[Dict[str, Any]], search: SearchFn, *, k: int, modes: Iterable[str] = MODES):
    per_item: List[Dict[str, Any]] = []
    for item in items:
        row: Dict[str, Any] = {"id": item["id"]}
        for mode in modes:
            row[mode] = score_item(search(item["question"], mode), item["gold_sources"], k)
        per_item.append(row)

    summary = {}
    for mode in modes:
        n = len(per_item) or 1
        summary[mode] = {
            metric: sum(row[mode][metric] for row in per_item) / n for metric in ("recall", "hit", "rr")
        }
    return per_item, summary


def render_markdown(per_item, summary, *, k: int, collection: str, modes: Sequence[str] = MODES) -> str:
    lines = [
        f"# Retrieval pilot: Recall@{k}, dense vs. hybrid",
        "",
        f"Collection `{collection}`, {len(per_item)} benchmark items with gold sources. "
        "Generated by `qdrant/eval_recall.py`; do not edit by hand.",
        "",
        f"| Mode | Recall@{k} | Hit@{k} | MRR@{k} |",
        "|---|---|---|---|",
    ]
    for mode in modes:
        s = summary[mode]
        lines.append(f"| {mode} | {s['recall']:.3f} | {s['hit']:.3f} | {s['rr']:.3f} |")

    lines += ["", "## Per item", "", "| Item | " + " | ".join(f"{m} R@{k}" for m in modes) + " |"]
    lines.append("|---|" + "---|" * len(modes))
    for row in per_item:
        lines.append(f"| {row['id']} | " + " | ".join(f"{row[m]['recall']:.2f}" for m in modes) + " |")
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Recall@k pilot for dense vs. hybrid retrieval.")
    parser.add_argument("--class-id", default=os.environ.get("EVAL_CLASS_ID"))
    parser.add_argument("--collection", required=True)
    parser.add_argument("--benchmark", default=str(REPO_DIR / "data" / "benchmark" / "single_turn.jsonl"))
    parser.add_argument("--k", type=int, default=5)
    parser.add_argument("--limit-items", type=int, default=None, help="Only the first N gold items.")
    parser.add_argument("--out", default=None, help="Write the markdown table here.")
    parser.add_argument("--env-file", default=str(ENV_FILE_PATH))
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    load_env_file(Path(args.env_file))
    if not args.class_id:
        print("Pass --class-id or set EVAL_CLASS_ID.", file=sys.stderr)
        return 1

    items = load_gold_items(Path(args.benchmark))[: args.limit_items]
    if not items:
        print("No benchmark items with gold_sources.", file=sys.stderr)
        return 1

    from qdrant_client import QdrantClient

    from jobs.search_content import run_search

    client = QdrantClient(url=os.environ["QDRANT_URL"], api_key=os.environ.get("QDRANT_API_KEY") or None)

    def search(query: str, mode: str) -> List[Dict[str, Any]]:
        result = run_search(
            client, query=query, class_id=args.class_id, limit=args.k, mode=mode, collection_name=args.collection
        )
        return result["hits"]

    per_item, summary = evaluate(items, search, k=args.k)
    markdown = render_markdown(per_item, summary, k=args.k, collection=args.collection)
    print(markdown)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(markdown, encoding="utf-8")
        print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
