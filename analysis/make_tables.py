#!/usr/bin/env python3
"""LaTeX booktabs tables for the paper from committed results (J4).

    python analysis/make_tables.py [--results results] [--out paper/tables] [--traj-run <runId>]

Writes:
  paper/tables/single_turn_ablation.tex   A0-A3, means ± 95% bootstrap CI over items
  paper/tables/memory_comparison.tex      M0/M1/M1b/M2, means ± 95% bootstrap CI over trajectories

Each file starts with a comment naming the results files it came from. A table whose inputs do
not exist yet is skipped with a message, never written with made-up numbers.
Include in the paper with \\input{tables/<name>} (needs \\usepackage{booktabs}).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import (  # noqa: E402
    ABLATION_ORDER,
    CI,
    MEMORY_ORDER,
    PAPER_DIR,
    REPO_DIR,
    RESULTS_DIR,
    TrajectoryRun,
    latest_single_turn_runs,
    load_single_turn,
    load_trajectory_runs,
    pick_trajectory_run,
    single_turn_cis,
)

# (key, header, higher_is_better)
SINGLE_TURN_COLUMNS: List[Tuple[str, str, bool]] = [
    ("correctness", r"Correct.\,$\uparrow$", True),
    ("faithfulness", r"Faithful.\,$\uparrow$", True),
    ("citation_precision", r"Cit.\ prec.\,$\uparrow$", True),
    ("recall_at_5", r"R@5\,$\uparrow$", True),
    ("abstention", r"Abst.\ acc.\,$\uparrow$", True),
]

MEMORY_COLUMNS: List[Tuple[str, str, bool]] = [
    ("nextActionAccuracy", r"Next-act.\,$\uparrow$", True),
    ("gapF1", r"Gap F1\,$\uparrow$", True),
    ("turnsToDetection", r"Turns\,$\downarrow$", False),
    ("unnecessaryRemediation", r"Unnec.\ rem.\,$\downarrow$", False),
    ("misconceptionPersistenceRate", r"Persist.\,$\uparrow$", True),
    ("brier", r"Brier\,$\downarrow$", False),
    ("auc", r"AUC\,$\uparrow$", True),
]

ABLATION_LABELS = {
    "A0": "A0 no retrieval",
    "A1": "A1 + dense RAG",
    "A2": "A2 + hybrid RAG",
    "A3": "A3 + critic",
}
MEMORY_LABELS = {
    "M0": "M0 none",
    "M1": "M1 raw history",
    "M1b": "M1b summary",
    "M2": "M2 structured",
}


def latex_escape(text: str) -> str:
    return text.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")


def format_ci(ci: Optional[CI], digits: int = 2, bold: bool = False) -> str:
    if ci is None:
        return "--"
    body = f"{ci.mean:.{digits}f} \\pm {ci.half_width:.{digits}f}"
    return f"$\\mathbf{{{body}}}$" if bold else f"${body}$"


def best_rows(values: Dict[str, Optional[CI]], higher_is_better: bool) -> set:
    """Rows holding the best mean (ties all bold); nothing is bold with fewer than 2 values."""
    present = {row: ci.mean for row, ci in values.items() if ci is not None}
    if len(present) < 2:
        return set()
    target = max(present.values()) if higher_is_better else min(present.values())
    return {row for row, mean in present.items() if abs(mean - target) < 1e-12}


def render_table(
    *,
    rows: Sequence[str],
    labels: Dict[str, str],
    columns: Sequence[Tuple[str, str, bool]],
    cells: Dict[str, Dict[str, Optional[CI]]],
    caption: str,
    label: str,
    sources: Sequence[str],
    digits: Dict[str, int] | None = None,
) -> str:
    digits = digits or {}
    bold = {key: best_rows({row: cells[row].get(key) for row in rows}, higher) for key, _, higher in columns}
    lines = [f"% Generated by analysis/make_tables.py from {', '.join(sources)}. Do not edit by hand."]
    lines += [
        r"\begin{table}[t]",
        r"\centering",
        r"\footnotesize",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{l" + "c" * len(columns) + "}",
        r"\toprule",
        "Condition & " + " & ".join(header for _, header, _ in columns) + r" \\",
        r"\midrule",
    ]
    for row in rows:
        values = [format_ci(cells[row].get(key), digits.get(key, 2), row in bold[key]) for key, _, _ in columns]
        lines.append(f"{latex_escape(labels.get(row, row))} & " + " & ".join(values) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def single_turn_table(paths: Dict[str, Path]) -> Optional[str]:
    rows_by_config = load_single_turn(paths)
    configs = [c for c in ABLATION_ORDER if c in rows_by_config]
    if not configs:
        return None
    cells = {config: single_turn_cis(rows_by_config[config]) for config in configs}
    n = max(len(rows) for rows in rows_by_config.values())
    return render_table(
        rows=configs,
        labels=ABLATION_LABELS,
        columns=SINGLE_TURN_COLUMNS,
        cells=cells,
        caption=f"Single-turn ablation (mean $\\pm$ 95\\% bootstrap CI half-width over up to {n} benchmark items).",
        label="tab:single-turn-ablation",
        sources=[str(paths[c].relative_to(REPO_DIR)).replace("\\", "/") if paths[c].is_relative_to(REPO_DIR) else paths[c].name for c in configs],
    )


def memory_table(run: TrajectoryRun) -> Optional[str]:
    conditions = [c for c in MEMORY_ORDER if c in run.conditions]
    if not conditions:
        return None
    cells = {c: {key: CI.from_summary(run.conditions[c].get(key)) for key, _, _ in MEMORY_COLUMNS} for c in conditions}
    flags = run.summary.get("flags", {})
    n = max(run.conditions[c].get("trajectories", 0) for c in conditions)
    sim = flags.get("sim", "?")
    return render_table(
        rows=conditions,
        labels=MEMORY_LABELS,
        columns=MEMORY_COLUMNS,
        cells=cells,
        caption=(
            f"Memory comparison on multi-turn trajectories ({sim} student, {n} trajectories per condition; "
            "mean $\\pm$ 95\\% bootstrap CI half-width). Calibration is defined for M2 only."
        ),
        label="tab:memory-comparison",
        sources=[f"results/trajectories/{run.run_id}.summary.json"],
        digits={"turnsToDetection": 1},
    )


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--results", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out", type=Path, default=PAPER_DIR / "tables")
    parser.add_argument("--traj-run", default=None, help="Trajectory run id (default: the run with the most conditions).")
    args = parser.parse_args(argv)

    outputs = {
        "single_turn_ablation.tex": single_turn_table(latest_single_turn_runs(args.results)),
    }
    run = pick_trajectory_run(load_trajectory_runs(args.results), args.traj_run)
    outputs["memory_comparison.tex"] = memory_table(run) if run else None

    args.out.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        if content is None:
            print(f"skip {name}: no results yet")
            continue
        (args.out / name).write_text(content, encoding="utf-8")
        print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
