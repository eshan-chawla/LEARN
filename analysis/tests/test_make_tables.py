from __future__ import annotations

from common import CI
from make_tables import best_rows, format_ci, latex_escape, main


def test_format_ci_and_bold():
    assert format_ci(CI(0.62, 0.59, 0.65, 10)) == r"$0.62 \pm 0.03$"
    assert format_ci(CI(0.5, 0.4, 0.6, 3), bold=True) == r"$\mathbf{0.50 \pm 0.10}$"
    assert format_ci(None) == "--"
    assert format_ci(CI(4.2, 3.2, 5.2, 2), digits=1) == r"$4.2 \pm 1.0$"


def test_best_rows_direction_ties_and_single_value():
    values = {"a": CI(0.2, 0, 0, 1), "b": CI(0.8, 0, 0, 1), "c": CI(0.8, 0, 0, 1), "d": None}
    assert best_rows(values, True) == {"b", "c"}
    assert best_rows(values, False) == {"a"}
    assert best_rows({"a": CI(0.2, 0, 0, 1), "b": None}, True) == set()


def test_latex_escape():
    assert latex_escape("p01_chain & 5%") == r"p01\_chain \& 5\%"


def test_main_writes_both_tables(results_dir, tmp_path):
    out = tmp_path / "tables"
    assert main(["--results", str(results_dir), "--out", str(out)]) == 0

    single = (out / "single_turn_ablation.tex").read_text()
    assert single.startswith("% Generated by analysis/make_tables.py from ")
    for needle in [r"\toprule", r"\midrule", r"\bottomrule", r"\label{tab:single-turn-ablation}", "A0 no retrieval", "A3 + critic"]:
        assert needle in single
    a0 = next(line for line in single.splitlines() if line.startswith("A0"))
    assert a0.count("--") == 3  # no retrieval: no citation precision, recall or faithfulness
    a3 = next(line for line in single.splitlines() if line.startswith("A3"))
    assert r"\mathbf" in a3  # best faithfulness / recall in the synthetic data

    memory = (out / "memory_comparison.tex").read_text()
    assert "results/trajectories/smoke-scripted-s1.summary.json" in memory.splitlines()[0]
    assert r"\label{tab:memory-comparison}" in memory
    m0 = next(line for line in memory.splitlines() if line.startswith("M0"))
    m2 = next(line for line in memory.splitlines() if line.startswith("M2"))
    assert m0.endswith(r"-- & -- \\")  # no calibration without structured state
    assert r"\mathbf{0.75 \pm 0.10}" in m2  # best next-action accuracy
    assert r"\mathbf{0.20 \pm 0.10}" in m2  # lowest unnecessary remediation is bold too


def test_missing_results_are_skipped_not_invented(tmp_path, capsys):
    empty = tmp_path / "results"
    (empty / "single_turn").mkdir(parents=True)
    (empty / "trajectories").mkdir()
    out = tmp_path / "tables"
    assert main(["--results", str(empty), "--out", str(out)]) == 0
    assert list(out.iterdir()) == []
    assert capsys.readouterr().out.count("skip") == 2
